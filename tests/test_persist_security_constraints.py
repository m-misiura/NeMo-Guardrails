import importlib.util
import subprocess
import tempfile
import unittest
from pathlib import Path
from unittest import mock

from packaging.version import Version

SCRIPT = Path(__file__).resolve().parents[1] / "scripts/persist-security-constraints.py"
spec = importlib.util.spec_from_file_location("persist_security_constraints", SCRIPT)
hook = importlib.util.module_from_spec(spec)
assert spec.loader is not None
spec.loader.exec_module(hook)


def upgrade(name="urllib3", version="2.8.0", **overrides):
    return {
        "depName": name,
        "newVersion": version,
        "depType": "indirect",
        "isVulnerabilityAlert": True,
        "prBodyNotes": ["Fixes TEST-ONLY-urllib3"],
        **overrides,
    }


class PersistSecurityConstraintsTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        (self.root / "dependencies").mkdir()
        (self.root / "requirements.txt").write_text(
            "# This file was autogenerated by uv via the following command:\n"
            "#    uv pip compile pyproject.toml --output-file=requirements.txt\n"
            "urllib3==2.8.0 \\\n    --hash=sha256:example\n"
        )
        (self.root / "dependencies/cve-constraints.txt").write_text(
            "# Existing downstream policy\nurllib3>=2.7,<3,!=2.7.1\n"
        )

    def test_persists_floor_and_recompiles(self):
        with mock.patch.object(hook.subprocess, "run") as compiler:
            self.assertTrue(hook.persist(self.root, [upgrade()]))

        compiler.assert_called_once_with(
            ["uv", "pip", "compile", "pyproject.toml", "--output-file=requirements.txt"],
            cwd=self.root,
            check=True,
        )
        contents = (self.root / "dependencies/cve-constraints.txt").read_text()
        self.assertIn("urllib3>=2.8.0", contents)
        self.assertIn("# Advisories: TEST-ONLY-urllib3", contents)
        self.assertIn("urllib3>=2.7,<3,!=2.7.1", contents)

    def test_skips_direct_and_non_security_updates(self):
        with mock.patch.object(hook.subprocess, "run") as compiler:
            self.assertFalse(
                hook.persist(
                    self.root,
                    [
                        upgrade(depType="project.dependencies"),
                        upgrade(isVulnerabilityAlert=False),
                    ],
                )
            )

        compiler.assert_not_called()

    def test_preserves_manual_and_stronger_automated_constraints(self):
        manual = '# Keep this bound\nurllib3>=2.9,<3; python_version < "3.13"\n'
        stronger = hook.merge_constraints(manual, {"urllib3": (Version("2.10"), {"TEST-ONLY-first"})})
        merged = hook.merge_constraints(stronger, {"urllib3": (Version("2.8"), {"TEST-ONLY-second"})})

        self.assertTrue(merged.startswith(manual))
        self.assertIn("urllib3>=2.10\n", merged)
        self.assertNotIn("urllib3>=2.8\n", merged)
        self.assertIn("TEST-ONLY-first, TEST-ONLY-second", merged)

    def test_missing_or_unresolved_package_fails_before_writing(self):
        before = (self.root / "dependencies/cve-constraints.txt").read_bytes()
        for candidate in [upgrade(version="3.0"), upgrade(name="missing-package")]:
            with self.assertRaises(ValueError), mock.patch.object(hook.subprocess, "run") as compiler:
                hook.persist(self.root, [candidate])

            compiler.assert_not_called()
            self.assertEqual((self.root / "dependencies/cve-constraints.txt").read_bytes(), before)

    def test_compile_failure_restores_constraints_and_requirements(self):
        before = {
            path: path.read_bytes()
            for path in [self.root / "requirements.txt", self.root / "dependencies/cve-constraints.txt"]
        }

        def failing_compile(*args, **kwargs):
            (self.root / "requirements.txt").write_text("partial output\n")
            raise subprocess.CalledProcessError(1, args[0])

        with (
            mock.patch.object(hook.subprocess, "run", side_effect=failing_compile),
            self.assertRaises(subprocess.CalledProcessError),
        ):
            hook.persist(self.root, [upgrade()])

        self.assertEqual(
            {
                path: path.read_bytes()
                for path in [self.root / "requirements.txt", self.root / "dependencies/cve-constraints.txt"]
            },
            before,
        )


if __name__ == "__main__":
    unittest.main()
